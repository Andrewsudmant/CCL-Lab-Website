#!/usr/bin/env python3
"""Generate deterministic Quarto fragments and canonical detail/theme pages."""

from __future__ import annotations
import html
import shutil
import sys
from pathlib import Path
from typing import Any

try:
    from .content import ROOT, load_records, research_scope, theme_index, load_yaml
    from .validate_content import validate_all
except ImportError:
    from content import ROOT, load_records, research_scope, theme_index, load_yaml
    from validate_content import validate_all

OUT = ROOT / "generated"


def esc(value: Any) -> str:
    return html.escape(str(value), quote=True)


def write_fragment(name: str, body: str) -> None:
    path = OUT / name
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text("<!-- Generated by scripts/generate_site.py; do not edit. -->\n```{=html}\n" + body.rstrip() + "\n```\n", encoding="utf-8")


def write_page(path: Path, title: str, description: str, body: str) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(f'---\ntitle: "{title.replace(chr(34), chr(39))}"\ndescription: "{description.replace(chr(34), chr(39))}"\n---\n\n<!-- Generated by scripts/generate_site.py; do not edit. -->\n\n{body.rstrip()}\n', encoding="utf-8")


def labels(ids: list[str]) -> list[str]:
    themes = theme_index()
    return [themes[item]["name"] for item in ids]


def tags(items: list[str], css: str = "tag-list") -> str:
    return f'<ul class="{css}">' + "".join(f"<li>{esc(item)}</li>" for item in items) + "</ul>"


def linked_tags(primary: str, secondary: list[str]) -> str:
    themes = theme_index()
    values = [(primary, "Primary")] + [(item, "Related") for item in secondary]
    return '<ul class="tag-list">' + "".join(f'<li><a href="/research/themes/{esc(item)}.html">{esc(themes[item]["name"])}</a><span class="sr-only"> ({kind})</span></li>' for item, kind in values) + "</ul>"


def record_card(record: dict[str, Any], kind: str) -> str:
    themes = [record["primary_theme"], *record["secondary_themes"]]
    relation = record.get("relationship_to_lab", "").replace("-", " ").title()
    meta = " · ".join(filter(None, [relation, record.get("status"), record.get("venue"), str(record.get("publication_date", ""))[:4]]))
    href = f"/{kind}/{record['record_id']}.html"
    return f'''<article class="record-card" data-themes="{esc(' '.join(themes))}">
  <p class="record-kicker">{esc(meta.replace('-', ' ').title())}</p>
  <h3><a href="{href}">{esc(record["title"])}</a></h3>
  <p>{esc(record.get("summary") or record.get("abstract_summary"))}</p>
  {linked_tags(record["primary_theme"], record["secondary_themes"])}
</article>'''


def generate_themes(projects: list[dict[str, Any]], publications: list[dict[str, Any]], watch: list[dict[str, Any]]) -> None:
    themes = research_scope()["themes"]
    home = ['<div class="theme-grid">']
    details = ['<div class="detail-grid">']
    for index, theme in enumerate(themes, 1):
        badge = '<span class="theme-status developing">Developing</span>' if theme["status"] == "developing" else ""
        home.append(f'''<article class="theme-card"><span class="theme-number">0{index}</span>{badge}<h3><a href="/research/themes/{esc(theme["id"])}.html">{esc(theme["name"])}</a></h3><p>{esc(theme["definition"])}</p></article>''')
        details.append(f'''<article class="detail-card" id="{esc(theme["id"])}"><div class="detail-index">0{index}</div><div>{badge}<h2><a href="/research/themes/{esc(theme["id"])}.html">{esc(theme["name"])}</a></h2><p>{esc(theme["definition"])}</p><p><a class="text-link" href="/research/themes/{esc(theme["id"])}.html">View projects, publications and recent evidence →</a></p></div><aside class="detail-meta"><strong>Status</strong><span>{esc(theme["status"].title())}</span><strong>Geographic priorities</strong><span>{esc(', '.join(theme["geographical_priorities"]))}</span><strong>Methods of interest</strong><span>{esc(', '.join(theme["methodological_interests"]))}</span></aside></article>''')

        core_projects = [p for p in projects if p["primary_theme"] == theme["id"]]
        related_projects = [p for p in projects if theme["id"] in p["secondary_themes"]]
        core_pubs = [p for p in publications if p["primary_theme"] == theme["id"]]
        related_pubs = [p for p in publications if theme["id"] in p["secondary_themes"]]
        recent = [w for w in watch if w["theme_assignments"]["primary"]["theme_id"] == theme["id"] or theme["id"] in [x["theme_id"] for x in w["theme_assignments"]["secondary"]]]
        def list_links(items: list[dict[str, Any]], kind: str) -> str:
            if not items: return '<p class="empty-compact">No verified records are published in this view yet.</p>'
            return '<div class="compact-list">' + ''.join(f'<p><a href="/{kind}/{esc(x["record_id"])}.html">{esc(x["title"])}</a></p>' for x in items) + '</div>'
        recent_html = '<div class="compact-list">' + ''.join(f'<p><a href="{esc(x["url"])}">{esc(x["title"])}</a><br><span>AI-selected and summarized · not reviewed by the lab</span></p>' for x in recent) + '</div>' if recent else '<p class="empty-compact">No recent Research Watch item is assigned here.</p>'
        body = f'''<p class="page-deck">{esc(theme["definition"])}</p>

::: {{.notice}}
**Theme status: {theme["status"].title()}.** Themes overlap. Records below are canonical entries cross-listed by primary or secondary relationship.
:::

## Core projects

```{{=html}}
{list_links(core_projects, 'projects')}
```

## Related projects

```{{=html}}
{list_links(related_projects, 'projects')}
```

## Core publications

```{{=html}}
{list_links(core_pubs, 'publications')}
```

## Related publications

```{{=html}}
{list_links(related_pubs, 'publications')}
```

## Recent evidence

```{{=html}}
{recent_html}
```

[Read the Research Watch method](/research-watch/methods.html).'''
        write_page(ROOT / "research/themes" / f'{theme["id"]}.qmd', theme["name"], theme["definition"], body)
    home.append("</div>")
    details.append("</div>")
    write_fragment("home-themes.qmd", "\n".join(home))
    write_fragment("research-themes.qmd", "\n".join(details))


def generate_people() -> None:
    cards = ['<div class="record-list">']
    for person in load_records("data/people"):
        links = " · ".join(f'<a href="{esc(x["url"])}">{esc(x["label"])}</a>' for x in person["profile_links"])
        cards.append(f'''<article class="record-card person-card"><p class="record-kicker">{esc(person["academic_title"])} · {esc(person["lab_role"])}</p><h2>{esc(person["name"])}</h2><p>{esc(person["short_bio"])}</p><p><a href="mailto:{esc(person["email"])}">{esc(person["email"])}</a></p><p>{links}</p>{tags(labels(person["themes"]))}</article>''')
    cards.append("</div>")
    write_fragment("people.qmd", "\n".join(cards))


def generate_projects(projects: list[dict[str, Any]], publications: list[dict[str, Any]]) -> None:
    groups = [("Current lab research", "current-lab-research"), ("Foundational and prior work", "foundational-prior-work"), ("Associated collaborations", "associated-collaboration")]
    listing = []
    for heading, key in groups:
        items = [p for p in projects if p["relationship_to_lab"] == key]
        if items:
            listing.append(f'<section class="relationship-group"><h2>{heading}</h2><div class="record-list">' + ''.join(record_card(p, "projects") for p in items) + '</div></section>')
    write_fragment("projects.qmd", ''.join(listing))
    pubs = {p["record_id"]: p for p in publications}
    for p in projects:
        sources = "\n".join((f'- [{x["label"]}]({x["url"]})' if x.get("url") else f'- {x["label"]}') + f' — verified {x["retrieved_date"]}' for x in p["authoritative_sources"])
        connections = "\n".join(f'- [{pubs[x]["title"]}](/publications/{x}.html)' for x in p["connected_publications"]) or "No connected publication is recorded."
        body = f'''<p class="page-deck">{p["summary"]}</p>

**Status:** {p["status"].replace('-', ' ').title()}  
**Relationship to the lab:** {p["relationship_to_lab"].replace('-', ' ').title()} — {p["relationship_note"]}  
**Primary theme:** [{theme_index()[p["primary_theme"]]["name"]}](/research/themes/{p["primary_theme"]}.html)  
**Related themes:** {', '.join(f'[{theme_index()[x]["name"]}](/research/themes/{x}.html)' for x in p["secondary_themes"]) or 'None'}

## Research questions

{chr(10).join('- ' + x for x in p["research_questions"])}

## Scope

- **Geography:** {', '.join(p["geographies"])}
- **Governance scales:** {', '.join(p["governance_scales"])}
- **Methods:** {', '.join(p["methods"])}
- **Climate domains:** {', '.join(p["climate_domains"])}
- **Sectors:** {', '.join(p["sectors"])}

## Connected publications

{connections}

## Authoritative sources

{sources}

**Record verification:** {p["verification_status"].replace('-', ' ').title()} · last verified {p["last_verified_date"]}.'''
        write_page(ROOT / "projects" / f'{p["record_id"]}.qmd', p["title"], p["summary"], body)


def generate_publications(publications: list[dict[str, Any]], projects: list[dict[str, Any]]) -> None:
    groups = [("Current lab outputs", "current-lab-research"), ("Selected foundational publications", "foundational-prior-work"), ("Associated and collaborative outputs", "associated-collaboration")]
    listing = []
    for heading, key in groups:
        items = [p for p in publications if p["relationship_to_lab"] == key]
        if items:
            listing.append(f'<section class="relationship-group"><h2>{heading}</h2><div class="record-list">' + ''.join(record_card(p, "publications") for p in items) + '</div></section>')
    write_fragment("publications.qmd", ''.join(listing))
    project_map = {p["record_id"]: p for p in projects}
    for p in publications:
        projects_md = "\n".join(f'- [{project_map[x]["title"]}](/projects/{x}.html)' for x in p["connected_projects"]) or "No connected project is recorded."
        id_line = f'**DOI:** [{p["doi"]}](https://doi.org/{p["doi"]})' if p["doi"] else f'**Identifier:** {", ".join(p["other_identifiers"])}'
        body = f'''<p class="page-deck">{p["abstract_summary"]}</p>

**Authors:** {', '.join(p["authors"])}  
**Published:** {p["publication_date"]} · {p["venue"]} · {p["publication_type"].replace('-', ' ').title()}  
**Relationship to the lab:** {p["relationship_to_lab"].replace('-', ' ').title()} — {p["relationship_note"]}  
{id_line}

> {p["citation"]}

[Open the original source]({p["url"]})

## Research relationships

**Primary theme:** [{theme_index()[p["primary_theme"]]["name"]}](/research/themes/{p["primary_theme"]}.html)  
**Related themes:** {', '.join(f'[{theme_index()[x]["name"]}](/research/themes/{x}.html)' for x in p["secondary_themes"]) or 'None'}

## Connected projects

{projects_md}

## Metadata provenance

Metadata sources: {', '.join(p["metadata_sources"])} · last verified {p["last_verified_date"]} · status: {p["verification_status"].replace('-', ' ')}. Dates are displayed only to the precision supplied by the verified record.'''
        write_page(ROOT / "publications" / f'{p["record_id"]}.qmd', p["title"], p["abstract_summary"], body)


def watch_card(record: dict[str, Any]) -> str:
    reviewed = record["review"]["status"] == "reviewed"
    badge = "Lab reviewed" if reviewed else "AI-selected and summarized · not reviewed by the lab"
    css = "reviewed" if reviewed else "unreviewed"
    themes = [record["theme_assignments"]["primary"]["theme_id"], *[x["theme_id"] for x in record["theme_assignments"]["secondary"]]]
    stable = record["stable_identifier"]
    identifier = f'{stable["type"].upper()}: {stable["value"]}' if stable else "No stable identifier"
    return f'''<article class="watch-card {css}" data-theme="{esc(' '.join(themes))}" data-source="{esc(record["source_type"])}">
  <span class="status-badge {css}">{esc(badge)}</span>
  <h3><a href="{esc(record["url"])}">{esc(record["title"])}</a></h3>
  <p class="record-meta">{esc(record["source_name"])} · {esc(record["publication_date"])} · {esc(record["source_type"].replace('-', ' '))}</p>
  <p>{esc(record["short_summary"])}</p><p><strong>Why it may matter</strong><br>{esc(record["reason_for_relevance"])}</p>
  {linked_tags(themes[0], themes[1:])}
  <details><summary>Provenance and limitations</summary><dl class="provenance"><dt>Identifier</dt><dd>{esc(identifier)}</dd><dt>Retrieved</dt><dd>{esc(record["retrieval_timestamp"])}</dd><dt>Evidence used</dt><dd>{esc(record["evidence_basis"]["description"])}</dd><dt>Limitation</dt><dd>{esc(record["evidence_basis"]["limitations"])}</dd><dt>Model / prompt</dt><dd>{esc(record["ai_provenance"]["model"] or "Not used")} · {esc(record["ai_provenance"]["prompt_version"])}</dd><dt>Confidence</dt><dd>{esc(record["confidence"]["label"])} ({record["confidence"]["score"]:.2f})</dd></dl></details>
</article>'''


def generate_watch(watch: list[dict[str, Any]]) -> None:
    reviewed = [x for x in watch if x["review"]["status"] == "reviewed"]
    automated = [x for x in watch if x["review"]["status"] == "not_reviewed"]
    write_fragment("research-watch-reviewed.qmd", '<div class="watch-grid">' + (''.join(watch_card(x) for x in reviewed) or '<p class="empty-compact">No lab-reviewed selections are published yet.</p>') + '</div>')
    write_fragment("research-watch-automated.qmd", '<div class="watch-grid" id="watch-results">' + ''.join(watch_card(x) for x in automated) + '</div>')
    write_fragment("home-watch.qmd", '<div class="home-watch-list">' + ''.join(watch_card(x) for x in automated[:6]) + '</div>')


def generate_all() -> None:
    errors = validate_all()
    if errors:
        raise ValueError("content validation failed:\n" + "\n".join(errors))
    OUT.mkdir(exist_ok=True)
    for directory in (ROOT / "projects", ROOT / "publications", ROOT / "research/themes"):
        if directory.exists():
            shutil.rmtree(directory)
    projects = load_records("data/projects")
    publications = load_records("data/publications")
    watch = load_records("data/research-watch/published")
    generate_themes(projects, publications, watch)
    generate_people()
    generate_projects(projects, publications)
    generate_publications(publications, projects)
    generate_watch(watch)


def main() -> int:
    try:
        generate_all()
    except ValueError as exc:
        print(exc)
        return 1
    print("Generated canonical listings, detail pages, theme views and Research Watch fragments.")
    return 0


if __name__ == "__main__":
    sys.exit(main())
